#!/usr/bin/env python3
"""Generate a small C++ address map from a SigmaStudio PARAM.h file."""

import argparse
import json
import re
import sys
from pathlib import Path


def normalize(text):
    """normalize SigmaStudio module names"""
    return re.sub(r"\s+", "", text.strip().upper())


def parse_param_header(path):
    """read parameter addresses from SigmaStudio header"""
    text = path.read_text(encoding="utf-8", errors="replace")
    groups = {}

    # SigmaStudio starts each module section with a comment
    blocks = re.split(r"(?=/\*\s*Module\s)", text)

    for block in blocks:
        comment = re.search(
            r"/\*\s*Module\s+(.+?)\s+-\s*.*?\*/",
            block,
            re.DOTALL,
        )
        count = re.search(
            r"^\s*#define\s+MOD_([A-Z0-9_]+)_COUNT\b",
            block,
            re.MULTILINE,
        )

        if not comment or not count:
            continue

        child = normalize(comment.group(1))

        if child.startswith("VOLUME"):
            role = "volume"
            parameter = "TARGET"
        elif child.startswith("USER_MUTE"):
            role = "user_mute"
            parameter = "MUTE"
        elif child.startswith("INIT_MUTE"):
            role = "init_mute"
            parameter = "MUTE"
        else:
            continue

        module = count.group(1)
        suffix = "_" + child

        # remove the child module name to get its parent name
        if not module.endswith(suffix):
            continue

        parent = module[:-len(suffix)]
        prefix = f"MOD_{module}_"
        addresses = []

        # find the matching *_ADDR macro
        for line in block.splitlines():
            match = re.match(r"\s*#define\s+(\w+)\s+(.+?)\s*$", line)
            if not match:
                continue

            macro, rhs = match.groups()
            if not macro.startswith(prefix) or not macro.endswith("_ADDR"):
                continue

            parameter_name = macro[len(prefix):-len("_ADDR")]
            if parameter_name.endswith(parameter):
                addresses.append(int(rhs, 0))

        if len(addresses) != 1:
            raise ValueError(
                f"Expected one {role} address in {module}, found {len(addresses)}"
            )

        group = groups.setdefault(parent, {})
        if role in group:
            raise ValueError(f"Duplicate {role} address: {parent}")

        group[role] = addresses[0]

    return groups


def sort_key(name):
    match = re.search(r"_(\d+)$", name)
    return int(match.group(1)) if match else 1, name.lower()


def generate(param_header):
    groups = parse_param_header(param_header)

    # keep only parent modules for which both addresses were found
    complete = [
        (name, values)
        for name, values in groups.items()
        if "volume" in values and "user_mute" in values and "init_mute" in values
    ]
    complete.sort(key=lambda item: sort_key(item[0]))

    if not complete:
        raise ValueError("No output processing modules found.")

    output = [
        "// Generated by sigmastudio_codegen.py",
        f"// Source: {param_header.name}",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace adau1452 {",
        "",
        "struct ParameterRef {",
        "    std::uint16_t address;",
        "};",
        "",
        "struct OutputProcessing {",
        "    const char* name;",
        "    ParameterRef volume;",
        "    ParameterRef user_mute;",
        "    ParameterRef init_mute;",
        "};",
        "",
        "inline constexpr OutputProcessing output_processing[] = {",
    ]

    for name, values in complete:
        volume_address = values["volume"]
        user_mute_address = values["user_mute"]
        init_mute_address = values["init_mute"]
        output.append(
            f"    {{{json.dumps(name)}, "
            f"{{0x{volume_address:04X}}}, "
            f"{{0x{user_mute_address:04X}}},"
            f"{{0x{init_mute_address:04X}}}}},"
        )

    output.extend([
        "};",
        "",
        "inline constexpr std::size_t output_processing_count =",
        "    sizeof(output_processing) / sizeof(output_processing[0]);",
        "",
        "} // namespace adau1452",
        "",
    ])

    return "\n".join(output)


def main():
    parser = argparse.ArgumentParser(
        description="Convert SigmaStudio parameter addresses to a C++ header."
    )
    parser.add_argument(
        "param_header",
        type=Path,
        help="SigmaStudio *_PARAM.h file",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path("./components/adau1452/include/dsp_mapping.hpp"),
        help="Output C++ header path",
    )
    args = parser.parse_args()

    try:
        result = generate(args.param_header)
        args.output.write_text(result, encoding="utf-8", newline="\n")
    except (OSError, ValueError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1

    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
